-- Additive runtime controls. Existing 8.1 clients do not read these tables and
-- continue to use the existing API and schema unchanged.
CREATE TABLE IF NOT EXISTS public.app_runtime_configuration (
  id boolean PRIMARY KEY DEFAULT true CHECK (id),
  minimum_supported_version text NOT NULL DEFAULT '8.1.0',
  recommended_version text NOT NULL DEFAULT '8.2.0',
  maintenance_message_it text,
  maintenance_message_en text,
  feature_flags jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(feature_flags) = 'object'),
  release_notes jsonb NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(release_notes) = 'array'),
  updated_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.app_runtime_configuration ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE public.app_runtime_configuration FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.app_runtime_configuration TO service_role;

