CREATE TABLE IF NOT EXISTS public.notification_delivery_attempts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  notification_id uuid,
  user_id uuid REFERENCES public.profiles(id) ON DELETE SET NULL,
  provider text NOT NULL DEFAULT 'expo',
  status text NOT NULL CHECK (status IN ('queued', 'sent', 'retryable_error', 'permanent_error')),
  provider_code text,
  latency_ms integer CHECK (latency_ms IS NULL OR latency_ms >= 0),
  attempted_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.notification_delivery_attempts ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE public.notification_delivery_attempts FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.notification_delivery_attempts TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.notification_delivery_attempts_id_seq TO service_role;

CREATE INDEX IF NOT EXISTS notification_delivery_attempts_attempted_at_idx
  ON public.notification_delivery_attempts (attempted_at DESC);
CREATE INDEX IF NOT EXISTS notification_delivery_attempts_user_id_attempted_at_idx
  ON public.notification_delivery_attempts (user_id, attempted_at DESC)
  WHERE user_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS notification_delivery_attempts_status_attempted_at_idx
  ON public.notification_delivery_attempts (status, attempted_at DESC);

COMMENT ON TABLE public.app_runtime_configuration IS
  'Server-owned client compatibility, staged feature flags, and localized release notes.';
COMMENT ON TABLE public.notification_delivery_attempts IS
  'Service-role-only delivery telemetry without push tokens or message bodies.';
